        TryParse(value, out var parsed)
            ? parsed
            : throw new ArgumentException(
                $"RevisionId must be a git SHA (7..64 hex chars): '{value}'.", nameof(value));

    public static bool TryParse([NotNullWhen(true)] string? value,
        [NotNullWhen(true)] out RevisionId? parsed)
    {
        parsed = null;
        if (string.IsNullOrWhiteSpace(value)) return false;
        var v = value.Trim();
        if (v.Length < 7 || v.Length > 64 || !IdentifierValidation.IsHex(v)) return false;
        parsed = new RevisionId(v);
        return true;
    }

    public override string ToString() => Value;
}

/// <summary>H-01.2.6: canonical symbol identity (BF-13.4 StableKey format).</summary>
public sealed record SymbolKey
{
    public const string KindCodes = "TMPFS";
    public string Value { get; }
    private SymbolKey(string value) => Value = value;

    public static SymbolKey FromStableKey(string value) =>
        TryParse(value, out var parsed)
            ? parsed
            : throw new ArgumentException(
                "Invalid SymbolKey (expected kind|assembly|fqn with kind in {T,M,P,F,S}): " +
                $"'{value}'.", nameof(value));

    public static bool TryParse([NotNullWhen(true)] string? value,
        [NotNullWhen(true)] out SymbolKey? parsed)
    {
        parsed = null;
        if (string.IsNullOrWhiteSpace(value)) return false;
        var v = value.Trim();
        var segments = v.Split('|');
        if (segments.Length < 3) return false;
        if (segments[0].Length != 1 || !KindCodes.Contains(segments[0][0])) return false;
        parsed = new SymbolKey(v);
        return true;
    }

    public override string ToString() => Value;
}

/// <summary>H-01.2.5: fusion grouping key (symbol or file - BF-14.1 contract).</summary>
public sealed record TargetKey
{
    public string Value { get; }
    public TargetKeyKind Kind { get; }
    private TargetKey(string value, TargetKeyKind kind) => (Value, Kind) = (value, kind);

    public static TargetKey FromSymbol(SymbolKey symbol)
    {
        if (symbol is null) throw new ArgumentNullException(nameof(symbol));
        return new TargetKey(symbol.Value, TargetKeyKind.Symbol);
    }

    public static TargetKey FromFile(string filePath)
    {
        var v = IdentifierValidation.NonEmpty(filePath, nameof(filePath)).Replace('\\', '/');
        return new TargetKey($"FILE|{v}", TargetKeyKind.File);
    }

    /// <summary>Legacy adoption path (H-01.7): wraps existing string keys as-is.</summary>
    public static TargetKey FromRaw(string raw)
    {
        var v = IdentifierValidation.NonEmpty(raw, nameof(raw));
        return new TargetKey(v, Classify(v));
    }

    private static TargetKeyKind Classify(string v)
    {
        if (v.StartsWith("FILE|", StringComparison.Ordinal)) return TargetKeyKind.File;
        var first = v.Split('|')[0];
        if (first.Length == 1 && SymbolKey.KindCodes.Contains(first[0])) return TargetKeyKind.Symbol;
        return TargetKeyKind.Other;
    }

    public override string ToString() => Value;
}

/// <summary>H-01.2.7: source location identity (file + optional line).</summary>
public sealed record LocationId
{
    public string Value { get; }
    private LocationId(string value) => Value = value;

    public static LocationId Create(string filePath, int? lineNumber = null)
    {
        var v = IdentifierValidation.NonEmpty(filePath, nameof(filePath)).Replace('\\', '/');
        return lineNumber is null
            ? new LocationId($"LOC|{v}")
            : new LocationId($"LOC|{v}|L{lineNumber.Value}");
    }

    public static bool TryParse([NotNullWhen(true)] string? value,
        [NotNullWhen(true)] out LocationId? parsed)
    {
        parsed = null;
        if (string.IsNullOrWhiteSpace(value)) return false;
        var v = value.Trim();
        if (!v.StartsWith("LOC|", StringComparison.Ordinal)) return false;
        var segments = v.Split('|');
        if (segments.Length < 2 || segments.Length > 3) return false;
        if (segments.Length == 3 && (segments[2].Length < 2 || segments[2][0] != 'L'
            || !int.TryParse(segments[2].AsSpan(1), out _))) return false;
        parsed = new LocationId(v);
        return true;
    }

    public override string ToString() => Value;
}