using System;
using System.Diagnostics.CodeAnalysis;
using System.Linq;

namespace ISCM.BugFinder.Core.Contracts;

/// <summary>
/// H-01.2: Canonical Identifier Contract.
/// Ten typed identities replacing naked string joins (audit X-005).
/// Rules:
///   - Value equality (records): same value == same identity.
///   - Validation in factories; TryParse for external/untrusted input.
///   - NO generation inside Core (no Guid.NewGuid / DateTime.Now) -
///     callers inject raw values (determinism, audit X-003 / H-13.3).
///   - Formats:
///       FailureSignature   FS-&lt;64 hex&gt;   content-derived (generated in H-02)
///       FailureId          F-&lt;64 hex&gt;    logical failure, signature-derived
///       FailureInstanceId  FI|&lt;FailureId&gt;|&lt;ExecutionSessionId&gt;
///       EvidenceId         EV-&lt;32 hex&gt;   provider-injected (hash in H-08.9)
///       ExecutionSessionId ES-&lt;32 hex&gt;
///       InvestigationId    INV-&lt;32 hex&gt;
///       RevisionId         git SHA (7..64 hex)
///       SymbolKey          &lt;K&gt;|&lt;Assembly&gt;|&lt;FQN&gt;&lt;(params)&gt;  (BF-13.4 StableKey)
///       TargetKey          SymbolKey | FILE|&lt;path&gt;           (BF-14.1 grouping key)
///       LocationId         LOC|&lt;path&gt;|L&lt;line?&gt;
///   JSON converters for these types land with H-01.3 (schema versioning).
/// </summary>
public enum TargetKeyKind { Symbol, File, Other }

internal static class IdentifierValidation
{
    public static string NonEmpty(string value, string paramName)
    {
        if (string.IsNullOrWhiteSpace(value))
            throw new ArgumentException("Identifier value is required.", paramName);
        return value.Trim();
    }

    public static bool IsHex(string text) =>
        text.Length > 0 && text.All(c =>
            c is >= '0' and <= '9' or >= 'a' and <= 'f' or >= 'A' and <= 'F');

    public static bool MatchesPrefixedHex(string? value, string prefix, int hexLength)
    {
        if (value is null) return false;
        var v = value.Trim();
        return v.Length == prefix.Length + 1 + hexLength
            && v.StartsWith(prefix + "-", StringComparison.Ordinal)
            && IsHex(v[(prefix.Length + 1)..]);
    }
}

/// <summary>Shared base for prefixed-hex identifiers (FS/F/EV/ES/INV family).</summary>
public abstract record PrefixedHexIdentifier
{
    public string Value { get; }
    protected PrefixedHexIdentifier(string value) => Value = value;

    protected static string Validate(string value, string prefix, int hexLength, string paramName)
    {
        var v = IdentifierValidation.NonEmpty(value, paramName);
        if (!IdentifierValidation.MatchesPrefixedHex(v, prefix, hexLength))
            throw new ArgumentException(
                $"{prefix} identifier must match '{prefix}-<{hexLength} hex chars>': '{value}'.", paramName);
        return v;
    }

    protected static bool Matches(string? value, string prefix, int hexLength) =>
        IdentifierValidation.MatchesPrefixedHex(value, prefix, hexLength);
}

/// <summary>H-01.2.3: content-derived failure signature (generated by H-02.2).</summary>
public sealed record FailureSignature : PrefixedHexIdentifier
{
    public const string Prefix = "FS";
    public const int HexLength = 64;
    private FailureSignature(string value) : base(value) { }

    public static FailureSignature Create(string value) =>
        TryParse(value, out var parsed)
            ? parsed
            : throw new ArgumentException($"Invalid {Prefix} identifier: '{value}'.", nameof(value));

    public static bool TryParse([NotNullWhen(true)] string? value,
        [NotNullWhen(true)] out FailureSignature? parsed)
    {
        if (value is not null && Matches(value, Prefix, HexLength))
        {
            parsed = new FailureSignature(value.Trim());
            return true;
        }
        parsed = null;
        return false;
    }

    public sealed override string ToString() => Value;
}

