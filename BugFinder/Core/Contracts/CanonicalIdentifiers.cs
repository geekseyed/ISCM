/// <summary>H-01.2.2: one concrete occurrence of a failure (signature + session).</summary>
public sealed record FailureInstanceId
{
    public string Value { get; }
    public FailureId Failure { get; }
    public ExecutionSessionId Session { get; }

    private FailureInstanceId(string value, FailureId failure, ExecutionSessionId session)
        => (Value, Failure, Session) = (value, failure, session);

    public static FailureInstanceId Create(FailureId failure, ExecutionSessionId session)
    {
        if (failure is null) throw new ArgumentNullException(nameof(failure));
        if (session is null) throw new ArgumentNullException(nameof(session));
        return new FailureInstanceId($"FI|{failure.Value}|{session.Value}", failure, session);
    }

    public static bool TryParse([NotNullWhen(true)] string? value,
        [NotNullWhen(true)] out FailureInstanceId? parsed)
    {
        parsed = null;
        if (string.IsNullOrWhiteSpace(value)) return false;
        var segments = value.Trim().Split('|');
        if (segments.Length != 3 || segments[0] != "FI") return false;
        if (!FailureId.TryParse(segments[1], out var failure)) return false;
        if (!ExecutionSessionId.TryParse(segments[2], out var session)) return false;
        parsed = new FailureInstanceId(value.Trim(), failure, session);
        return true;
    }

    public override string ToString() => Value;
}

/// <summary>H-01.2.10: a git revision (full or short SHA).</summary>
